#!/usr/bin/env python3
"""Generate db/seed.sql for RoadRescue sample data.

Produces:
  - 1 admin + 15 customer accounts (APP_USER)
  - 12 shop-owner accounts (SHOP)
  - 22 service requests across all statuses

Passwords are hashed with BCrypt using the $2a$ prefix, because
RoadRescueApplication's startup runner only treats $2a$ as "already hashed".
"""
import bcrypt
import datetime
import json
import os

def h(pw: str) -> str:
    return bcrypt.hashpw(pw.encode(), bcrypt.gensalt(prefix=b"2a", rounds=10)).decode()

def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "''")

