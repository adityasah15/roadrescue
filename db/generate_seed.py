lines.append("SET FOREIGN_KEY_CHECKS = 0;")
lines.append("DELETE FROM service_request;")
lines.append("DELETE FROM shop;")
lines.append("DELETE FROM app_user WHERE role = 'CUSTOMER';")
lines.append("SET FOREIGN_KEY_CHECKS = 1;")
lines.append("")

