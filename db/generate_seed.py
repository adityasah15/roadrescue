lines.append(
    "INSERT INTO app_user (username, password, role) "
    "SELECT 'admin', '{0}', 'ADMIN' FROM DUAL "
    "WHERE NOT EXISTS (SELECT 1 FROM app_user WHERE username = 'admin');".format(admin_hash)
)

